-- Baseline: the schema Hibernate (ddl-auto=update) had created before Flyway was introduced,
-- i.e. everything up to and including the DrEmail feature (before PR #2).
--
-- Databases that already have these tables (production, older local copies) skip this file:
-- spring.flyway.baseline-on-migrate marks them as version 1 the first time Flyway runs.
-- Constraint names are the ones Hibernate generated, so new and existing databases match and
-- later migrations can refer to them by name.
--
-- Keep this file portable (PostgreSQL + H2 in PostgreSQL mode): the tests run it on H2.

CREATE TABLE users (
    id       bigint GENERATED BY DEFAULT AS IDENTITY,
    email    varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    username varchar(255) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT ukr43af9ap4edm43mmtq01oddj6 UNIQUE (username)
);

CREATE TABLE roles (
    id   bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(20),
    CONSTRAINT roles_pkey PRIMARY KEY (id),
    CONSTRAINT roles_name_check CHECK (name IN ('ADMIN', 'USER'))
);

CREATE TABLE user_roles (
    user_id bigint NOT NULL,
    role_id bigint NOT NULL,
    CONSTRAINT user_roles_pkey PRIMARY KEY (user_id, role_id),
    CONSTRAINT fkhfh9dx7w3ubf1co1vdev94g3f FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fkh8ciramu9cc9q3qcqiv4ue8a6 FOREIGN KEY (role_id) REFERENCES roles (id)
);

CREATE TABLE courses (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at   timestamp(6),
    credit_hours integer,
    description  varchar(1000),
    label        varchar(300) NOT NULL,
    name         varchar(255) NOT NULL,
    updated_at   timestamp(6),
    CONSTRAINT courses_pkey PRIMARY KEY (id)
);

CREATE TABLE comments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    content    varchar(4000) NOT NULL,
    created_at timestamp(6),
    updated_at timestamp(6),
    course_id  bigint NOT NULL,
    user_id    bigint NOT NULL,
    CONSTRAINT comments_pkey PRIMARY KEY (id),
    CONSTRAINT fk7ktrfqv6fgfuw6fvwludvibu4 FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk8omq0tc18jd43bu5tjh6jvraq FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE resource (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    books     varchar(1000),
    exams     varchar(1000),
    labs      varchar(1000),
    name      varchar(200),
    slides    varchar(1000),
    summaries varchar(1000),
    videos    varchar(1000),
    course_id bigint NOT NULL,
    user_id   bigint NOT NULL,
    CONSTRAINT resource_pkey PRIMARY KEY (id),
    CONSTRAINT fk4yoh5xabj1926lt7fcgh8sead FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk9rx1aalrihjvhx59gmmurhuns FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE tracking (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    completed boolean NOT NULL,
    mark      varchar(255),
    course_id bigint NOT NULL,
    user_id   bigint NOT NULL,
    CONSTRAINT tracking_pkey PRIMARY KEY (id),
