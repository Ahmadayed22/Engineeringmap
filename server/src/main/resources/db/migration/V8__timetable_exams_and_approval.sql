-- Weekly timetable, past exam bank, exam countdown, and admin approval for materials.
--
-- resource.approved: materials added by students wait for an admin before others see them.
-- Every material that already exists stays visible (DEFAULT true).

ALTER TABLE resource ADD COLUMN approved boolean NOT NULL DEFAULT true;

-- One row per class meeting in a student's week (a Sun/Tue/Thu lecture is three rows).
-- day_of_week: 0 = Sunday ... 6 = Saturday. Times are minutes after midnight.
CREATE TABLE timetable_entries (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id      bigint NOT NULL,
    course_id    bigint,
    title        varchar(100) NOT NULL,
    day_of_week  integer NOT NULL,
    start_minute integer NOT NULL,
    end_minute   integer NOT NULL,
    location     varchar(60),
    color        integer NOT NULL,
    CONSTRAINT timetable_entries_pkey PRIMARY KEY (id),
    CONSTRAINT fk_timetable_entries_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_timetable_entries_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE SET NULL
);

CREATE INDEX idx_timetable_entries_user ON timetable_entries (user_id);

-- Old exam papers per course. The file itself is in past_exam_files so listing exams never
-- loads it. Uploads by students start unapproved; admin uploads are approved at once.
CREATE TABLE past_exams (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    course_id     bigint NOT NULL,
    uploader_id   bigint NOT NULL,
    kind          varchar(20) NOT NULL,
    exam_year     integer NOT NULL,
    term          varchar(20) NOT NULL,
    doctor        varchar(100),
    with_solution boolean NOT NULL,
    file_name     varchar(150) NOT NULL,
    content_type  varchar(40) NOT NULL,
    size_bytes    integer NOT NULL,
    approved      boolean NOT NULL,
    created_at    timestamp(6),
    CONSTRAINT past_exams_pkey PRIMARY KEY (id),
    CONSTRAINT fk_past_exams_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_past_exams_uploader FOREIGN KEY (uploader_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_past_exams_course ON past_exams (course_id, approved);

CREATE TABLE past_exam_files (
    exam_id bigint NOT NULL,
    data    bytea NOT NULL,
    CONSTRAINT past_exam_files_pkey PRIMARY KEY (exam_id),
    CONSTRAINT fk_past_exam_files_exam FOREIGN KEY (exam_id) REFERENCES past_exams (id) ON DELETE CASCADE
);

-- A student's own upcoming exams, for the countdown page and the reminder notifications.
-- reminders_sent: 0 = none yet, 1 = the "3 days left" one, 2 = the "tomorrow" one.
CREATE TABLE exam_dates (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id        bigint NOT NULL,
    course_id      bigint,
    title          varchar(100) NOT NULL,
    kind           varchar(20) NOT NULL,
    starts_at      timestamp(6) with time zone NOT NULL,
    location       varchar(60),
    reminders_sent integer NOT NULL,
    CONSTRAINT exam_dates_pkey PRIMARY KEY (id),
    CONSTRAINT fk_exam_dates_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_dates_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE SET NULL
);

CREATE INDEX idx_exam_dates_user ON exam_dates (user_id);
CREATE INDEX idx_exam_dates_reminders ON exam_dates (reminders_sent, starts_at);
