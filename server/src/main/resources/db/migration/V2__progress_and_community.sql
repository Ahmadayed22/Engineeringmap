-- PR #2: progress tracking, planner, sharing and community features.
--
-- Written with IF NOT EXISTS because ddl-auto=update may already have created these objects on a
-- database that was baselined at version 1 (e.g. production, if PR #2 was deployed before
-- Flyway). On such a database every statement here is a no-op; on any other it creates them.
-- Constraints are inline so they are only created together with their table.

ALTER TABLE comments ADD COLUMN IF NOT EXISTS parent_id bigint;

CREATE TABLE IF NOT EXISTS resource_votes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    vote_value  integer NOT NULL,
    resource_id bigint NOT NULL,
    user_id     bigint NOT NULL,
    CONSTRAINT resource_votes_pkey PRIMARY KEY (id),
    CONSTRAINT ukavuyurwba8rpureswytkc6urd UNIQUE (resource_id, user_id),
    CONSTRAINT fk44n63cyt89ciwyqjvv558ilhp FOREIGN KEY (resource_id) REFERENCES resource (id) ON DELETE CASCADE,
    CONSTRAINT fkgrevq8nuvsawe4kxaf11pd3f3 FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS resource_reports (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at  timestamp(6),
    reason      varchar(500) NOT NULL,
    resolved    boolean NOT NULL,
    user_id     bigint NOT NULL,
    resource_id bigint NOT NULL,
    CONSTRAINT resource_reports_pkey PRIMARY KEY (id),
    CONSTRAINT fkb56nmv04t7gk3u04mfsgm3001 FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fkfm8a5090ghm359n8eefc8g79o FOREIGN KEY (resource_id) REFERENCES resource (id) ON DELETE CASCADE
);

