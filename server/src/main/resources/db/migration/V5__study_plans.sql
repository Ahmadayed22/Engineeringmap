-- Roadmaps (study plans) are now data: admins can create new ones (a new major or a new
-- version of one), rename, reorder and show/hide them. A new roadmap starts hidden.
-- `slug` is the short id used in URLs and in study_maps.plan / planned_courses.plan; it never
-- changes once created. CPE and EE keep their existing ids.

CREATE TABLE study_plans (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    slug       varchar(40) NOT NULL,
    name_ar    varchar(150) NOT NULL,
    name_en    varchar(150) NOT NULL,
    visible    boolean NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamp(6),
    CONSTRAINT study_plans_pkey PRIMARY KEY (id),
    CONSTRAINT uk_study_plans_slug UNIQUE (slug)
);

